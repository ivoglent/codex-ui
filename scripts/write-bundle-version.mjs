#!/usr/bin/env node
// Stamp the current bundle version into a generated module so the PWA can
// compare it against the version reported by the server. The release
// workflow passes APP_VERSION through the Dockerfile; local development
// falls back to the workspace package version.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..");
const webRoot = join(repoRoot, "apps/web");
const packageJsonPath = join(webRoot, "package.json");
const outputPath = join(webRoot, "src/app/bundle-version.generated.ts");

const envVersion = process.env.APP_VERSION?.trim();
let version = envVersion;
let commit = process.env.APP_COMMIT?.trim() || null;
if (!version) {
  const pkg = JSON.parse(readFileSync(packageJsonPath, "utf8"));
  version = pkg.version || "0.0.0";
}

const commitLiteral = commit ? JSON.stringify(commit) : "null";
const body =
  "// Auto-generated by scripts/write-bundle-version.mjs. Do not edit.\n" +
  `export const BUNDLE_VERSION: string = ${JSON.stringify(version)};\n` +
  `export const BUNDLE_COMMIT: string | null = ${commitLiteral};\n`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, body, "utf8");
console.log(`Wrote ${outputPath} (version=${version}, commit=${commit ?? "<unset>"})`);
